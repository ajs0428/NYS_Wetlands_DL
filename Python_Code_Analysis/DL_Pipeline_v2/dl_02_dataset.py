"""
dl_02_dataset.py

PyTorch Dataset class for wetland classification patches.
Handles normalization, one-hot encoding, and data loading.

Band names and normalization rules are read from normalization_stats.json,
which is generated by dl_01_compute_statistics.py.
"""

import json
import numpy as np
import rasterio
import torch
from torch.utils.data import Dataset, DataLoader
from pathlib import Path
from typing import Optional, Tuple, List, Dict, Callable
import random



def normalize_bands(
    data: np.ndarray,
    normalization: dict,
    predictor_names: List[str],
    nodata: Optional[float] = None
) -> np.ndarray:
    """
    Apply per-band normalization and one-hot encode categorical bands.

    Shared by WetlandPatchDataset (training) and dl_06_predict.py (inference).

    Args:
        data: Array of shape (num_predictors, H, W)
        normalization: Dict keyed by band name with normalization config
        predictor_names: Ordered list of predictor band names matching data axis 0
        nodata: NoData value from raster

    Returns:
        Normalized array of shape (in_channels, H, W) as float32
    """
    normalized_bands = []

    for i, band_name in enumerate(predictor_names):
        band = data[i]
        norm_config = normalization[band_name]
        method = norm_config["method"]

        # Create valid data mask
        valid_mask = ~np.isnan(band)
        if nodata is not None and not np.isnan(nodata):
            valid_mask &= (band != nodata)

        if method == "min_max":
            min_val = norm_config["min"]
            max_val = norm_config["max"]
            range_val = max_val - min_val

            if range_val > 0:
                normalized = (band - min_val) / range_val
            else:
                normalized = np.zeros_like(band)

            # Clip to [0, 1] and handle nodata
            normalized = np.clip(normalized, 0, 1)
            normalized = np.where(valid_mask, normalized, 0)
            normalized_bands.append(normalized)

        elif method == "shift_scale":
            shift = norm_config["shift"]
            scale = norm_config["scale"]
            normalized = (band + shift) / scale
            normalized = np.clip(normalized, 0, 1)
            normalized = np.where(valid_mask, normalized, 0)
            normalized_bands.append(normalized)

        elif method == "one_hot":
            num_classes = norm_config["num_classes"]
            class_range = norm_config.get("class_range", [1, num_classes])
            one_hot = np.zeros((num_classes, band.shape[0], band.shape[1]), dtype=np.float32)

            for class_idx in range(class_range[0], class_range[1] + 1):
                one_hot[class_idx - class_range[0]] = (band == class_idx).astype(np.float32)

            normalized_bands.extend([one_hot[j] for j in range(num_classes)])

    return np.stack(normalized_bands, axis=0).astype(np.float32)


class WetlandPatchDataset(Dataset):
    """
    PyTorch Dataset for wetland classification GeoTIFF patches.

    Features:
    - Lazy loading of patches via rasterio
    - Per-band normalization (min-max, shift-scale, one-hot)
    - NoData handling (unlabeled pixels set to ignore_index=255)
    - Returns (predictors, labels) tensors
    - Band configuration read dynamically from stats JSON
    """

    def __init__(
        self,
        patch_files: List[Path],
        stats_path: Path,
        augment: bool = False,
        validate_bands: bool = True,
        patch_size: Optional[int] = None,
        label_transform: Optional[Callable[[np.ndarray], np.ndarray]] = None,
    ):
        """
        Args:
            patch_files: List of paths to GeoTIFF patch files
            stats_path: Path to normalization_stats.json
            augment: Whether to apply data augmentation
            validate_bands: Check each file's band count AND spatial dimensions
                            at init (slower but catches bad patches upfront).
                            Set False if data is known-clean or on slow network
                            storage.
            patch_size: Expected square patch size (H == W == patch_size). If
                        None, it is inferred as the most common size across the
                        files. Patches whose H/W differ are skipped (a batch
                        cannot stack mismatched tensors).
            label_transform: Optional callable applied to the label array AFTER
                        nodata masking and the (binary) remap, e.g. the factorial
                        v2 `flddeg` seeded wetland->UPL degrade. Receives and
                        returns an int64 (H, W) array; ignore_index pixels must be
                        preserved. Applied to train/val datasets only (never test).
        """
        self.patch_files = patch_files
        self.augment = augment
        self.label_transform = label_transform

        # Load normalization statistics
        with open(stats_path) as f:
            self.stats = json.load(f)

        self.normalization = self.stats["normalization"]

        # Read band configuration from stats (set by dl_01_compute_statistics.py)
        self.band_names = self.stats["band_names"]
        self.label_band = self.stats["label_band"]
        self.predictor_names = self.stats["predictor_names"]
        self.label_index = self.band_names.index(self.label_band)
        self.class_names = self.stats["class_names"]
        self.num_classes = len(self.class_names)
        self.ignore_index = self.stats.get("ignore_index", 255)
        self.in_channels = self.stats["in_channels"]

        # Build label remap lookup table (for binary mode)
        remap = self.stats.get("label_remap")
        if remap:
            max_src = max(int(k) for k in remap)
            self._remap_lut = np.full(max(max_src + 1, 256), self.ignore_index, dtype=np.int64)
            for src, dst in remap.items():
                self._remap_lut[int(src)] = dst
            self._remap_lut[self.ignore_index] = self.ignore_index
        else:
            self._remap_lut = None

        # Build predictor band indices (into the raw raster)
        self.predictor_indices = [
            self.band_names.index(name) for name in self.predictor_names
        ]
        self._expected_bands = len(self.band_names)

        # Filter out patches with wrong band count or spatial size.
        # A batch's tensors are stacked, so every patch must share H x W;
        # one odd-sized patch (e.g. 292x292 among 256x256) otherwise crashes
        # collation with "stack expects each tensor to be equal size".
        self.patch_size = patch_size
        if validate_bands:
            # First pass: read band count + dims for each file.
            file_dims = []  # (path, count, height, width)
            for pf in self.patch_files:
                with rasterio.open(pf) as src:
                    file_dims.append((pf, src.count, src.height, src.width))

            # Determine the expected size: explicit arg, else the modal H x W.
            if self.patch_size is None:
                from collections import Counter
                size_counts = Counter((h, w) for _, _, h, w in file_dims)
                (exp_h, exp_w), _ = size_counts.most_common(1)[0]
            else:
                exp_h = exp_w = self.patch_size

            valid_files = []
            n_bad_bands = 0
            n_bad_size = 0
            for pf, count, h, w in file_dims:
                if count < self._expected_bands:
                    print(f"  Skipping {pf.name}: {count} bands "
                          f"(expected {self._expected_bands})")
                    n_bad_bands += 1
                elif h != exp_h or w != exp_w:
                    print(f"  Skipping {pf.name}: {h}x{w} "
                          f"(expected {exp_h}x{exp_w})")
                    n_bad_size += 1
                else:
                    valid_files.append(pf)

            if len(valid_files) < len(self.patch_files):
                print(f"  Filtered: {len(valid_files)}/{len(self.patch_files)} "
                      f"patches OK ({n_bad_bands} wrong band count, "
                      f"{n_bad_size} wrong size; expected {exp_h}x{exp_w})")
            self.patch_files = valid_files
            self.patch_size = exp_h if exp_h == exp_w else None

        # Build class weight tensor
        class_weights = self.stats.get("class_weights", {})
        self.class_weights = torch.tensor([
            class_weights.get(name, 1.0) for name in self.class_names
        ], dtype=torch.float32)

    def __len__(self) -> int:
        return len(self.patch_files)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor]:
        """
        Load and process a single patch.

        Returns:
            predictors: Tensor of shape (in_channels, H, W)
            labels: Tensor of shape (H, W) with class values
        """
        patch_path = self.patch_files[idx]

        with rasterio.open(patch_path) as src:
            if src.count < self._expected_bands:
                raise ValueError(
                    f"{patch_path.name} has {src.count} bands, expected "
                    f"{self._expected_bands}. Remove it or re-run dl_01_compute_statistics.py."
                )
            data = src.read().astype(np.float32)
            nodata = src.nodata

        # Separate predictors and labels by index
        predictors = data[self.predictor_indices]
        labels = data[self.label_index]

        # Handle NoData in labels -> ignore_index (excluded from loss)
        nodata_mask = np.isnan(labels)
        if nodata is not None and not np.isnan(nodata):
            nodata_mask |= (labels == nodata)

        labels = np.where(nodata_mask, self.ignore_index, labels).astype(np.int64)

        # Apply label remap (e.g., multiclass -> binary)
        if self._remap_lut is not None:
            labels = self._remap_lut[labels]

        # Optional label transform (e.g., factorial-v2 flddeg degrade); train/val only
        if self.label_transform is not None:
            labels = self.label_transform(labels)

        # Normalize predictors and one-hot encode categorical bands
        normalized = self._normalize_predictors(predictors, nodata)

        # Apply augmentation if enabled
        if self.augment:
            normalized, labels = self._augment(normalized, labels)

        return torch.from_numpy(normalized), torch.from_numpy(labels)

    def _normalize_predictors(
        self,
        predictors: np.ndarray,
        nodata: Optional[float]
    ) -> np.ndarray:
        """Apply per-band normalization. Delegates to module-level normalize_bands()."""
        return normalize_bands(predictors, self.normalization, self.predictor_names, nodata)

    def _augment(
        self,
        predictors: np.ndarray,
        labels: np.ndarray
    ) -> Tuple[np.ndarray, np.ndarray]:
        """
        Apply random augmentations.

        Geometric: flips, 90° rotations (label-safe)
        Spectral: Gaussian noise, per-band brightness jitter (predictors only)

        Args:
            predictors: Array of shape (in_channels, H, W)
            labels: Array of shape (H, W)

        Returns:
            Augmented predictors and labels
        """
        # --- Geometric (applied to both predictors and labels) ---
        # Defer .copy() — apply all view-based transforms first, then make
        # contiguous once at the end to avoid ~9MB allocation per transform.

        # Random horizontal flip
        if random.random() > 0.5:
            predictors = np.flip(predictors, axis=2)
            labels = np.flip(labels, axis=1)

        # Random vertical flip
        if random.random() > 0.5:
            predictors = np.flip(predictors, axis=1)
            labels = np.flip(labels, axis=0)

        # Random 90-degree rotations
        k = random.randint(0, 3)
        if k > 0:
            predictors = np.rot90(predictors, k, axes=(1, 2))
            labels = np.rot90(labels, k, axes=(0, 1))

        # Single contiguous copy for all geometric transforms
        predictors = np.ascontiguousarray(predictors)
        labels = np.ascontiguousarray(labels)

        # --- Spectral (applied to predictors only) ---

        # Gaussian noise (sigma 0.01-0.03, simulates sensor noise)
        if random.random() > 0.5:
            sigma = random.uniform(0.01, 0.03)
            noise = np.random.normal(0, sigma, predictors.shape).astype(np.float32)
            predictors = np.clip(predictors + noise, 0, 1)

        # Per-band brightness jitter (+-5%, simulates illumination variation)
        if random.random() > 0.5:
            scales = np.random.uniform(0.95, 1.05, size=(predictors.shape[0], 1, 1)).astype(np.float32)
            predictors = np.clip(predictors * scales, 0, 1)

        return predictors, labels

    def get_class_weights(self) -> torch.Tensor:
        """Return class weights for loss function."""
        return self.class_weights


def create_data_splits(
    patches_dir: Path,
    train_ratio: float = 0.70,
    val_ratio: float = 0.15,
    test_ratio: float = 0.15,
    seed: int = 42,
    n_patches: Optional[int] = None,
) -> Tuple[List[Path], List[Path], List[Path]]:
    """
    Split patch files into train/val/test sets.

    Args:
        patches_dir: Directory containing GeoTIFF patches
        train_ratio: Fraction for training
        val_ratio: Fraction for validation
        test_ratio: Fraction for testing
        seed: Random seed for reproducibility
        n_patches: If set, cap the pool to the first n_patches of the
            seed-shuffled file list before splitting (learning-curve studies).
            The train/val/test ratios still apply to the capped subset, and the
            subset is reproducible for a given seed.

    Returns:
        train_files, val_files, test_files
    """
    assert abs(train_ratio + val_ratio + test_ratio - 1.0) < 1e-6

    patch_files = sorted(patches_dir.glob("*.tif"))

    if not patch_files:
        raise ValueError(f"No .tif files found in {patches_dir}")

    # Shuffle with seed
    random.seed(seed)
    shuffled = patch_files.copy()
    random.shuffle(shuffled)

    # Optional patch-count cap (applied AFTER the seeded shuffle so the subset is
    # reproducible and nested: smaller n is a prefix of larger n for a given seed).
    if n_patches is not None:
        if n_patches < 1:
            raise ValueError(f"n_patches must be >= 1, got {n_patches}")
        if n_patches < len(shuffled):
            print(f"Capping patch pool: {len(shuffled)} -> {n_patches} (seed={seed})")
            shuffled = shuffled[:n_patches]
        else:
            print(f"n_patches={n_patches} >= available ({len(shuffled)}); using all patches")

    n = len(shuffled)
    train_end = int(n * train_ratio)
    val_end = train_end + int(n * val_ratio)

    train_files = shuffled[:train_end]
    val_files = shuffled[train_end:val_end]
    test_files = shuffled[val_end:]

    print(f"Data split (seed={seed}):")
    print(f"  Train: {len(train_files)} patches ({len(train_files)/n*100:.1f}%)")
    print(f"  Val:   {len(val_files)} patches ({len(val_files)/n*100:.1f}%)")
    print(f"  Test:  {len(test_files)} patches ({len(test_files)/n*100:.1f}%)")

    return train_files, val_files, test_files


def create_dataloaders(
    patches_dir: Path,
    stats_path: Path,
    batch_size: int = 16,
    num_workers: int = 4,
    seed: int = 42,
    n_patches: Optional[int] = None,
) -> Tuple[DataLoader, DataLoader, DataLoader, torch.Tensor]:
    """
    Create train/val/test DataLoaders.

    Args:
        patches_dir: Directory containing GeoTIFF patches
        stats_path: Path to normalization_stats.json
        batch_size: Batch size for DataLoaders
        num_workers: Number of worker processes
        seed: Random seed for data splitting
        n_patches: Optional cap on the patch pool (learning-curve studies);
            forwarded to create_data_splits.

    Returns:
        train_loader, val_loader, test_loader, class_weights
    """
    train_files, val_files, test_files = create_data_splits(
        patches_dir, seed=seed, n_patches=n_patches
    )

    train_dataset = WetlandPatchDataset(train_files, stats_path, augment=True)
    val_dataset = WetlandPatchDataset(val_files, stats_path, augment=False)
    test_dataset = WetlandPatchDataset(test_files, stats_path, augment=False)

    persist = num_workers > 0

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True,
        persistent_workers=persist,
        drop_last=True,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
        persistent_workers=persist,
    )

    test_loader = DataLoader(
        test_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
        persistent_workers=persist,
    )

    class_weights = train_dataset.get_class_weights()

    return train_loader, val_loader, test_loader, class_weights


def create_dataloaders_from_pools(
    config: str,
    seed: int,
    stats_dir: Path,
    mode: str = "multiclass",
    batch_size: int = 16,
    num_workers: int = 4,
    weight_power: float = 0.5,
    leakage_guard: Optional[str] = None,
    data_root: Optional[Path] = None,
    validate_bands: bool = True,
    label_transform: Optional[Callable[[np.ndarray], np.ndarray]] = None,
) -> Tuple[DataLoader, DataLoader, DataLoader, torch.Tensor]:
    """Factorial-v2 dataloaders: resolve a config's field-anchored pools, then build
    train/val/test loaders with the correct per-config, per-mode stats files.

    The (train, val, test) FILE lists come from ``dl_patch_pools.resolve_pools`` --
    test is always field (``R_Patches`` at the seed's held-out footprints), train/val
    from the config's label directory(ies) under the leakage guard. Classification
    ``mode`` is carried entirely by the stats file (its ``label_remap`` /
    ``class_names`` / ``class_weights``), so:

      * train + val use the config's own **TRAIN_STATS** (its label source's class
        weights drive the loss);
      * test uses the matching field config's **EVAL_STATS** -- same predictors and
        normalization (identical values; predictors are label-source-invariant), so
        the field test set is scored under the field config's stats per plan Sec. 3.

    ``flddeg`` needs the seeded degrade (``dl_degrade_labels.py``); until a
    ``label_transform`` is supplied this raises rather than silently training on
    undegraded field labels.

    Returns: train_loader, val_loader, test_loader, class_weights (from TRAIN_STATS).
    """
    import dl_experiment_config as X
    import dl_patch_pools as P

    if leakage_guard is None:
        leakage_guard = X.LEAKAGE_GUARD
    if data_root is None:
        data_root = P.DEFAULT_DATA_ROOT
    stats_dir = Path(stats_dir)

    if X.config_pool_rule(config) == "degrade" and label_transform is None:
        # flddeg: auto-build the seeded wetland->UPL degrade (train/val only). Its
        # flip probability is measured from the field/NWI dirs, so it needs no
        # pre-materialized labels; test stays undegraded (built without it below).
        from dl_degrade_labels import make_degrader
        label_transform = make_degrader(mode, seed, data_root=data_root)

    train_files, val_files, test_files = P.resolve_pools(
        config, seed, leakage_guard=leakage_guard, data_root=data_root
    )

    train_stats = stats_dir / X.stats_basename(config, mode=mode, weight_power=weight_power)
    eval_stats = stats_dir / X.stats_basename(X.eval_config_name(config), mode=mode, weight_power=weight_power)
    for p in (train_stats, eval_stats):
        if not p.exists():
            raise FileNotFoundError(f"stats file not found: {p} (run dl_make_config_stats.py --all --mode {mode})")

    train_dataset = WetlandPatchDataset(train_files, train_stats, augment=True,
                                        validate_bands=validate_bands, label_transform=label_transform)
    val_dataset = WetlandPatchDataset(val_files, train_stats, augment=False,
                                      validate_bands=validate_bands, label_transform=label_transform)
    test_dataset = WetlandPatchDataset(test_files, eval_stats, augment=False,
                                       validate_bands=validate_bands)  # test never degraded

    persist = num_workers > 0
    train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True, num_workers=num_workers,
                              pin_memory=True, persistent_workers=persist, drop_last=True)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False, num_workers=num_workers,
                            pin_memory=True, persistent_workers=persist)
    test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False, num_workers=num_workers,
                             pin_memory=True, persistent_workers=persist)

    print(f"[pools] {config} seed{seed} mode={mode} guard={leakage_guard}: "
          f"train={len(train_dataset)} val={len(val_dataset)} test={len(test_dataset)} "
          f"| train_stats={train_stats.name} eval_stats={eval_stats.name}")

    return train_loader, val_loader, test_loader, train_dataset.get_class_weights()


def create_kfold_splits(
    patches_dir: Path,
    n_folds: int = 5,
    seed: int = 42,
) -> List[Tuple[List[Path], List[Path]]]:
    """
    Create k-fold cross-validation splits.

    Args:
        patches_dir: Directory containing GeoTIFF patches
        n_folds: Number of folds
        seed: Random seed for reproducibility

    Returns:
        List of (train_files, val_files) tuples, one per fold.
    """
    from sklearn.model_selection import KFold

    patch_files = sorted(patches_dir.glob("*.tif"))
    if not patch_files:
        raise ValueError(f"No .tif files found in {patches_dir}")

    patch_array = np.array(patch_files)
    kf = KFold(n_splits=n_folds, shuffle=True, random_state=seed)

    folds = []
    for fold_idx, (train_idx, val_idx) in enumerate(kf.split(patch_array)):
        train_files = patch_array[train_idx].tolist()
        val_files = patch_array[val_idx].tolist()
        print(f"  Fold {fold_idx + 1}/{n_folds}: "
              f"Train={len(train_files)}, Val={len(val_files)}")
        folds.append((train_files, val_files))

    return folds


def create_fold_dataloaders(
    train_files: List[Path],
    val_files: List[Path],
    stats_path: Path,
    batch_size: int = 16,
    num_workers: int = 4,
) -> Tuple[DataLoader, DataLoader, torch.Tensor]:
    """
    Create train/val DataLoaders from explicit file lists (for k-fold CV).

    Args:
        train_files: List of training patch paths
        val_files: List of validation patch paths
        stats_path: Path to normalization_stats.json
        batch_size: Batch size for DataLoaders
        num_workers: Number of worker processes

    Returns:
        train_loader, val_loader, class_weights
    """
    train_dataset = WetlandPatchDataset(train_files, stats_path, augment=True)
    val_dataset = WetlandPatchDataset(val_files, stats_path, augment=False)

    persist = num_workers > 0

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=True,
        persistent_workers=persist,
        drop_last=True,
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=True,
        persistent_workers=persist,
    )

    class_weights = train_dataset.get_class_weights()
    return train_loader, val_loader, class_weights


